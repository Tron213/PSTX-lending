function roadmap_data() {
  $saved = read('roadmap');
  if (is_array($saved)
      && is_array($saved['stages'] ?? null)) {
    return $saved;
  }
  return ['stages' => roadmap_defaults(),
    'revision' => 'initial'];
}

function roadmap_action($method) {
  $data = roadmap_data();
  if ($method === 'GET') {
    $scope = $_GET['scope'] ?? '';
    if ($scope === 'admin') {
      require_admin();
      answer($data);
    }
    if ($scope !== '') fail('Неверный режим');
    $state = $_GET['state'] ?? '';
    if (!in_array($state,
        ['', 'idea', 'development', 'done'], true)) {
      fail('Неверный статус этапа');
    }
    answer(['stages' => array_values(
      array_filter($data['stages'],
        function ($stage) use ($state) {
          return $stage['visible']
            && ($state === ''
              || $stage['state'] === $state);
        }))]);
  }
  require_admin();
  if ($method !== 'PUT') {
    fail('Метод не поддерживается', 405);
  }
  csrf();
  $input = input();
  if (($input['revision'] ?? null)
      !== $data['revision']) {
    fail('План изменён в другом окне. '
      . 'Обновите страницу перед сохранением.', 409);
  }
  $stages = $input['stages'] ?? null;
  if (!is_array($stages) || count($stages) > 32) {
    fail('Допустимо до 32 этапов');
  }
  $clean = [];
  $seen = [];
  foreach ($stages as $stage) {
    if (!is_array($stage)
        || !valid_id($stage['id'] ?? null)
        || isset($seen[$stage['id']])) {
      fail('Неверный или повторный этап');
    }
    $state = $stage['state'] ?? '';
    $visible = $stage['visible'] ?? null;
    if (!in_array($state,
        ['idea', 'development', 'done'], true)
        || !is_bool($visible)) {
      fail('Проверьте статус и видимость');
    }
    $item = ['id' => $stage['id'],
      'state' => $state, 'visible' => $visible];
    foreach (['title' => 640,
        'description' => 20000,
        'criterion' => 8000, 'result' => 8000,
        'next' => 8000] as $key => $limit) {
      $item[$key] = trim(text_value(
        $stage, $key, $limit));
    }
    if ($item['title'] === ''
        || $item['description'] === '') {
      fail('У этапа нужны название '
        . 'и подробное описание задумки');
    }
    if ($state === 'done'
        && $item['result'] === '') {
      fail('Для статуса «Выполнено» '
        . 'опишите полученный результат');
    }
    $seen[$item['id']] = true;
    $clean[] = $item;
  }
  $saved = ['stages' => $clean,
    'revision' => bin2hex(random_bytes(12))];
  save('roadmap', $saved);
  answer($saved);
}
